import { writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { scanModuleUIs } from "./app/composables/compose";

// --- module-owned UI composition (build time only) ---
// A module ships UI by putting .vue components in modules/<name>/ui/;
// the shell's own components sit in engine/webui/app (it ships nothing under
// engine/webui/ui/), and engine-ring panels sit in engine/<name>/ui/
// (tier law, card t_ae5423d2); the ring lives under engine/.
// The scan (pure, in app/composables/compose.ts) discovers those dirs;
// this config (1) registers each as a Nuxt component directory with the
// module name as namespace prefix, and (2) generates the panel list the
// shell's inspector mounts. No runtime registry, no plugin protocol.
const uiRoot = dirname(fileURLToPath(import.meta.url)); // engine/webui/ under the checkout root
const repoRoot = resolve(uiRoot, "../.."); // the repo root (engine/webui is two levels deep)
const modulesRoot = resolve(repoRoot, "modules"); // modules/
const engineRoot = resolve(repoRoot, "engine"); // engine/ (agent, ai, http_channel, tui, webui)
const moduleUIs = scanModuleUIs(modulesRoot, engineRoot);

// One panel per module component file, imports relative to this dir.
// Written even when the list is empty: the shell's inspector imports it
// unconditionally, so the file must always exist (and stay constant
// when a clean clone checks out with no module shipping UI).
const composableDir = join(uiRoot, "app", "composables");
const panels = moduleUIs.flatMap((ui) =>
  ui.components.map((file) => ({
    module: ui.module,
    rel: relative(composableDir, join(ui.dir, file)).split("\\").join("/"),
    dockable: ui.dockable,
  })),
);
const banner =
  "// GENERATED by nuxt.config.ts (module-panels) - do not edit by hand.\n" +
  "// One entry per module UI component (<module>/ui/<File>.vue):\n" +
  "// modules/<name>/ui/ for the opinionated capsules, engine/<name>/ui/\n" +
  "// inside engine/ for the engine ring (http_channel, card t_ae5423d2).\n" +
  "// the shell's inspector mounts these through the composition. `dockable`\n" +
  "// is the module's ui/dockable.json declaration (the dockable contract,\n" +
  "// card t_30ee04fb) - null when the module ships none.\n";
const imports = [
  ...panels.map((p, i) => `import p${i} from "${p.rel}";`),
  'import type { DockableSpec } from "./dockables";',
].join("\n");
const entries = panels
  .map((p, i) => `  { module: "${p.module}", component: p${i}, dockable: ${JSON.stringify(p.dockable ?? null)} },`)
  .join("\n");
const source =
  banner +
  "\n" +
  (imports ? imports + "\n" : "") +
  "\nexport interface ModulePanel {\n  module: string;\n  component: any;\n  dockable?: DockableSpec | null;\n}\n\n" +
  "export const modulePanels: ModulePanel[] = [\n" +
  (entries ? entries + "\n" : "") +
  "];\n";
writeFileSync(join(composableDir, "module-panels.generated.ts"), source);

export default defineNuxtConfig({
  // omega webui: static SPA, served by the omega binary in production.
  // In dev, nitro devProxy forwards the API root paths to the locally
  // running dev omega on :8098 (the installed instance owns 8099).
  compatibilityDate: "2026-10-13",
  ssr: false,
  // full types for the editor (tsconfig.json extends .nuxt/tsconfig.json),
  // but no type-check in the build loop - it stays fast
  typescript: { strict: true, typeCheck: false },
  css: [
    "~/assets/css/main.css",
    // card t_67fc1905: the bottom panel's rules (mobile zero-collapse)
    // live apart from main.css - the drawer-repairs card owns main.css's
    // media block edits this round, so the panel gets its own file
    "~/assets/css/bottompanel.css",
  ],
  // Auto-import: the shell's own components keep their flat names (the
  // area folders are layout, not namespace); each module UI dir
  // registers with the module name as namespace prefix - Nuxt's
  // prefix/stem dedupe means ToolsList.vue in modules/tools/ui/
  // registers as ToolsList, while an unrelated stem lands under it
  // (tools + List.vue -> ToolsList). Modules keep their domain in file
  // stems, so shell names never collide.
  components: [
    { path: "~/components", pathPrefix: false },
    ...moduleUIs.map((ui) => ({
      path: ui.dir,
      prefix: ui.module,
      pathPrefix: true,
    })),
  ],
  nitro: {
    // OMEGA_DEV_API retargets the proxy for a private verify lane (the
    // drawer card's override, untouched); the paths cover every
    // endpoint the SPA + the inspector's module panels fetch in dev
    // (the module views are same-origin in production - embedded).
    devProxy: Object.fromEntries(
      [
        "/health", "/models", "/tools", "/chat", "/sessions", "/tasks",
        "/files", "/cron", "/skills", "/logs", "/settings", "/themes",
        "/commands", "/commands/dispatch", // t_07aed3f9: the palette's GET
        // /commands (extension registry rows) and POST /commands/dispatch
        // (module command + skill dispatch) fetch the API root in dev too
        "/modules", // t_8ac225f1: the settings tab's modules group fetches
        // the live introspection in dev too (same-origin embedded in
        // production) - without this route the group renders nothing
        "/disabled", // t_372b9e9a: the registry-browser tabs' fold reads
        // (GET /disabled, PUT /disabled/skills|tools|agents) in dev too
        "/boards",
        // card t_078a2c35: the canvas view-model pipe (GET /ui/canvas +
        // POST /ui/actions) is same-origin embedded in production; the
        // chat transcript renders FROM it (chat-last 2a), so a dev lane
        // without this route renders only the REST restore and cannot
        // reproduce canvas-seam behavior at all
        "/ui",
        // the sidebar's list fetch is QUERY-BEARING and devProxy matches
        // prefix on the FULL path (query included) - a bare "/sessions"
        // key never matches it (the remainder "?archived=include" is not
        // a "/..." path segment), so the request fell through to SSR
        // index.html and the SPA booted with an empty session list
        "/sessions?archived=include",
        // card t_14f73742: the extensions inventory tab fetches the
        // module list in dev (same-origin embedded in production)
        "/extensions",
        // t_8eb149fa: the workspace chip's browser fetches /workspaces/
        // browse (browseWorkspaces) - without this route a dev lane
        // serves SSR index.html for the pop and no dir rows render
        "/workspaces",
        // card t_e1e61680: the insights dashboard fetches GET /insights
        // (same-origin embedded in production)
        "/insights",
        // card t_c7136c50: the MCP tab's panel fetches GET /mcp/servers
        // (same-origin embedded in production)
        "/mcp",
        // card t_c7222095: the MERGED Agents tab fetches the agent
        // inventory + the continuous roster/wake surface in dev (the
        // same-origin reads in production) - without these routes the
        // rows load SSR HTML and the tab never boots
        "/agents",
        "/continuous",
      ].map(
        (p) => [
          p,
          // NOTE the parens: `??` binds looser than `+` - without them a
          // set OMEGA_DEV_API swallowed the path and every proxied
          // route fetched the target's SPA root (HTML instead of API)
          { target: (process.env.OMEGA_DEV_API ?? "http://127.0.0.1:8098") + p },
        ],
      )
      // The period switch: devProxy routes match by prefix on the FULL
      // request path (query included) and h3 rewrites the layer-relative
      // remainder onto the request - a bare-keyed route mangles
      // /insights?days=7 into /insights/?days=7 and the SPA eats its own
      // index.html as the "response" (the JSON parse blowup). The window
      // values are fixed literals (InsightsTab's four options), so give
      // each its own literal route with the query in BOTH key and target
      // - the two compose correctly through httpxy's targetPath +
      // targetSearch join (card t_d7fd3ad3's 79 period-switch step).
      .concat(
        [7, 30, 90, 0].map((d) => {
          const api = process.env.OMEGA_DEV_API ?? "http://127.0.0.1:8098";
          return [`/insights?days=${d}`, { target: `${api}/insights?days=${d}` }];
        }),
      ),
    ),
    output: {
      publicDir: "dist",
    },
  },
  app: {
    head: {
      title: "omega",
      meta: [
        { charset: "utf-8" },
        {
          name: "viewport",
          content:
            "width=device-width, initial-scale=1, interactive-widget=resizes-content",
        },
      ],
    },
  },
});