import { writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { scanModuleUIs } from "./app/composables/compose";
// the tab capsules' composition lives in the shell's dockable registry.
import { TAB_MODULES } from "./app/composables/dockables";

// module-owned UI composition (build time only) --- A module ships UI by. The scan
// (pure, in app/composables/compose.ts) discovers those dirs; this config (1) registers
// each as a Nuxt component directory with the module name as namespace prefix, and (2)
// generates the panel list the shell's inspector mounts and the tab list the dock's
// capsule outlets mount - ONE scan, TWO manifests, a capsule in exactly one of them:
// the tab capsules (TAB_MODULES) ride module-tabs.generated.ts, every other module UI
// rides module-panels.generated.ts.
const uiRoot = dirname(fileURLToPath(import.meta.url)); // webui/ at the checkout root (restructure part 2)
const repoRoot = resolve(uiRoot, ".."); // the repo root (webui sits at the root)
const modulesRoot = resolve(repoRoot, "harness"); // harness/
const shellRoot = resolve(repoRoot, "api"); // api/ (the serving shell)
const moduleUIs = scanModuleUIs(modulesRoot, shellRoot);

// the partition. A tab capsule is exactly one module whose ui/ ships ONE.vue tab view
// (the component app.vue's outlet binds); the scan found more or fewer than one -> the
// build dies loud.
const tabModuleSet = new Set<string>(TAB_MODULES);
const panelUIs = moduleUIs.filter((ui) => !tabModuleSet.has(ui.module));
const tabUIs = moduleUIs.filter((ui) => tabModuleSet.has(ui.module));

// One panel per module component file, imports relative to this dir.
// Written even when the list is empty: the shell's inspector imports it
// unconditionally, so the file must always exist (and stay constant
// when a clean clone checks out with no module shipping UI).
const composableDir = join(uiRoot, "app", "composables");
const panels = panelUIs.flatMap((ui) =>
  ui.components.map((file) => ({
    module: ui.module,
    rel: relative(composableDir, join(ui.dir, file)).split("\\").join("/"),
    dockable: ui.dockable,
  })),
);
const tabs = tabUIs.map((ui) => {
  if (ui.components.length !== 1) {
    throw new Error(
      `module-tabs: "${ui.module}" ships ${ui.components.length} ui/ views ` +
        `(${ui.components.join(", ")}) - a tab capsule's ui/ carries exactly ` +
        "one .vue tab view (dockables.ts TAB_MODULES, card t_617c2ad0)",
    );
  }
  return {
    module: ui.module,
    rel: relative(composableDir, join(ui.dir, ui.components[0])).split("\\").join("/"),
    dockable: ui.dockable,
  };
});
const banner =
  "// GENERATED by nuxt.config.ts (module-panels) - do not edit by hand.\n" +
  "// One entry per module UI component (<module>/ui/<File>.vue): harness/<name>/ui/\n" +
  "// for the opinionated capsules, api/<name>/ui/ for the serving shell. The tab\n" +
  "// capsules (dockables.ts TAB_MODULES) are NOT listed here - their one tab view\n" +
  "// rides module-tabs.generated.ts, so a capsule appears in exactly one of the\n" +
  "// two manifests. `dockable` is the module's ui/dockable.json declaration, null\n" +
  "// when the module ships none.\n";
const imports = [
  ...panels.map((p, i) => `import p${i} from "${p.rel}";`),
  'import type { DockableSpec } from "./dockables";',
].join("\n");
const entries = panels
  .map((p, i) => `  { module: "${p.module}", component: p${i}, dockable: ${JSON.stringify(p.dockable ?? null)} },`)
  .join("\n");
const source =
  banner +
  "\n" +
  (imports ? imports + "\n" : "") +
  "\nexport interface ModulePanel {\n  module: string;\n  component: any;\n  dockable?: DockableSpec | null;\n}\n\n" +
  "export const modulePanels: ModulePanel[] = [\n" +
  (entries ? entries + "\n" : "") +
  "];\n";
writeFileSync(join(composableDir, "module-panels.generated.ts"), source);

// the TAB capsules' manifest: dockables.ts calls them the pinned-root tabs (terminal /
// browser / notifications); the shell's dock outlets import the components from here,
// never a hardcoded path.
const tabsBanner =
  "// GENERATED by nuxt.config.ts (module-tabs) - do not edit by hand.\n" +
  "// One entry per tab capsule (dockables.ts TAB_MODULES): the module ships ONE\n" +
  "// tab view at harness/<name>/ui/<File>.vue; `dockable` is its ui/dockable.json.\n";
const tabImports = [
  ...tabs.map((p, i) => `import t${i} from "${p.rel}";`),
  'import type { DockableSpec } from "./dockables";',
].join("\n");
const tabEntries = tabs
  .map((p, i) => `  { module: "${p.module}", component: t${i}, dockable: ${JSON.stringify(p.dockable ?? null)} },`)
  .join("\n");
const tabsSource =
  tabsBanner +
  "\n" +
  (tabImports ? tabImports + "\n" : "") +
  "\nexport interface ModuleTab {\n  module: string;\n  component: any;\n  dockable?: DockableSpec | null;\n}\n\n" +
  "export const moduleTabs: ModuleTab[] = [\n" +
  (tabEntries ? tabEntries + "\n" : "") +
  "];\n";
writeFileSync(join(composableDir, "module-tabs.generated.ts"), tabsSource);

export default defineNuxtConfig({
  compatibilityDate: "2026-10-13",
  ssr: false,
  typescript: { strict: true, typeCheck: false },
  css: [
    "~/assets/css/main.css",
    // the bottom panel's rules (mobile zero-collapse) live apart from main.css.
    "~/assets/css/bottompanel.css",
    // THE ROW LAW - one registry-row anatomy.
    "~/assets/css/registry-row.css",
  ],
  // Auto-import: the shell's own components keep their flat names.
  // Modules keep their domain in file stems, so shell names never collide.
  components: [
    { path: "~/components", pathPrefix: false },
    ...moduleUIs.map((ui) => ({
      path: ui.dir,
      prefix: ui.module,
      pathPrefix: true,
    })),
  ],
  nitro: {
    // OMEGA_DEV_API retargets the proxy for a private verify lane.
    devProxy: Object.fromEntries(
      [
        "/health", "/models", "/tools", "/chat", "/sessions", "/tasks",
        "/files", "/cron", "/skills", "/logs", "/settings", "/themes",
        // the terminal tab's claim/stream/input/resize/kill face: without this the dev
        // lane answers the SPA's terminal calls with SSR HTML and the pane never leaves
        // "connecting...", so no journey can exercise the shell in dev
        "/terminal",
        "/commands", "/commands/dispatch", //: the palette's GET
        // /commands (extension registry rows) and POST /commands/dispatch.
        "/modules", //: the settings tab's modules group fetches
        "/disabled", //: the registry-browser tabs' fold reads
        // (GET /disabled, PUT /disabled/skills|tools|agents) in dev too
        "/boards",
        // the canvas view-model pipe (GET /ui/canvas + POST /ui/actions) is same-origin
        // embedded in production; the chat transcript renders FROM it (chat-last 2a),
        // so a dev lane without this route renders only the REST restore and cannot
        // reproduce canvas-seam behavior at all
        "/ui",
        // the sidebar's list fetch is QUERY-BEARING and devProxy matches prefix on the
        // FULL path (query included) - a bare "/sessions" key never matches it (the
        // remainder "?archived=include" is not a "/." path segment), so the request
        // fell through to SSR index.html and the SPA booted with an empty session list
        "/sessions?archived=include",
        "/extensions",
        // the workspace chip's browser fetches /workspaces/ browse (browseWorkspaces).
        "/workspaces",
        // the insights dashboard fetches GET /insights.
        "/insights",
        // the MCP tab's panel fetches GET /mcp/servers.
        "/mcp",
        // the MERGED Agents tab fetches the agent inventory + the continuous
        // roster/wake surface in dev (the same-origin reads in production) - without
        // these routes the rows load SSR HTML and the tab never boots
        "/agents",
        "/continuous",
      ].map(
        (p) => [
          p,
          // NOTE the parens: `??` binds looser than `+`.
          { target: (process.env.OMEGA_DEV_API ?? "http://127.0.0.1:8098") + p },
        ],
      )
      // The period switch: devProxy routes match by prefix on the FULL request path.
      .concat(
        [7, 30, 90, 0].map((d) => {
          const api = process.env.OMEGA_DEV_API ?? "http://127.0.0.1:8098";
          return [`/insights?days=${d}`, { target: `${api}/insights?days=${d}` }];
        }),
      ),
    ),
    output: {
      publicDir: "dist",
    },
  },
  app: {
    head: {
      title: "omega",
      meta: [
        { charset: "utf-8" },
        {
          name: "viewport",
          content:
            "width=device-width, initial-scale=1, interactive-widget=resizes-content",
        },
      ],
    },
  },
});